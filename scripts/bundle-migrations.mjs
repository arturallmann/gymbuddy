// Bundles the generated migrations in drizzle/ into src/db/migrations.ts,
// because the app cannot read files from drizzle/ at runtime.
// Run through `npm run db:generate`.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

export function buildMigrationsModule(root = '.') {
  const journal = JSON.parse(readFileSync(`${root}/drizzle/meta/_journal.json`, 'utf8'));
  const migrations = journal.entries.map((entry) => {
    const sql = readFileSync(`${root}/drizzle/${entry.tag}.sql`, 'utf8');
    return {
      tag: entry.tag,
      when: entry.when,
      hash: createHash('sha256').update(sql).digest('hex'),
      statements: sql
        .split('--> statement-breakpoint')
        .map((statement) => statement.trim())
        .filter((statement) => statement.length > 0),
    };
  });
  return (
    '// Generated by scripts/bundle-migrations.mjs. Do not edit by hand.\n' +
    'export type Migration = {\n' +
    '  tag: string;\n' +
    '  when: number;\n' +
    '  hash: string;\n' +
    '  statements: string[];\n' +
    '};\n\n' +
    `export const migrations: Migration[] = ${JSON.stringify(migrations, null, 2)};\n`
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('src/db/migrations.ts', buildMigrationsModule());
  console.log('Wrote src/db/migrations.ts');
}
